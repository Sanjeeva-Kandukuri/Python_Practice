# Variables

# Definition --> variables are like containers, they store values you can change their values whenever you need.

# Basic variable assignment 

product_name = "loptop"
price = 50000
in_stock = True
print(product_name,price,in_stock)

# Multiple assignment

a, b ,c = 10,20,30
print(a,b,c)

# we can also assign the same value to multiple variables
x = y = z = 100
print(x,y,z)

# Swapping variables
a, b = 10,20
a,b = b,a
print(a,b)

# Deleting Variables

x = 10
del x
print(x)
